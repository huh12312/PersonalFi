/**
 * WP 2.12 seed extensions: standalone, deterministic fixtures for three of
 * the five scenarios the dispatch names ("the Phase 2 engines need for a
 * fair gate" — subscription with price change, card migration, duplicate
 * service, credit overspend, quiet-hours notification).
 *
 * ## Why this is a separate module, not a change to `generateDemoData`
 *
 * `generateDemoData(1)`'s default output (982 transactions, 32 merchants, 6
 * accounts) is pinned, by exact count, across Phase 1 and Phase 2 evidence
 * (`docs/evidence/phase-1/wp1.7-quality.md` §5, `apps/api/test/db/
 * phase1-seed-e2e.test.ts`, `packages/contexts/ledger/test/seed.test.ts`,
 * and others). Adding a second credit-card account or a new recurring plan
 * to the default household would shift every one of those pinned counts —
 * exactly the kind of silent, cross-cutting change this project's own gate
 * lessons warn about. This module is additive instead: a second, independent
 * `SeedAccount`/`SeedTransaction` set, generated by its own deterministic RNG
 * stream, for a caller that explicitly wants these scenarios and is prepared
 * to load them (e.g. as extra transactions synced onto a fresh account pair)
 * rather than a household nobody asked for appearing in the default demo.
 *
 * ## What is here, and what is deliberately not
 *
 * - **Subscription with a price change** — already covered by
 *   `generateDemoData`'s own "Adobe Creative Cloud" plan
 *   (`transactions.ts`'s `RECURRING_PLANS`, `priceIncreaseAtMonth: 12`) and
 *   by `dataset.labels.recurringSeries[].priceIncrease` — not duplicated
 *   here.
 * - **Card migration** (`generateCardMigration`) — one subscription stream
 *   that bills on one credit card for the first half of the window, then a
 *   reissued/replaced card for the second half. The 07 §2.2 shape WP 2.2's
 *   own corpus already covers in isolation
 *   (`packages/contexts/recurring/test/corpora/synthetic.ts`'s
 *   `CARD_MIGRATION` injection) — this module gives the *ledger-shaped*
 *   fixture (real `SeedAccount`/`SeedTransaction` rows) a UI/API-level gate
 *   walk needs, which the recurring engine's own pure-function corpus does
 *   not produce.
 * - **Duplicate service** (`generateDuplicateService`) — two concurrently
 *   active subscriptions in the same category (two video-streaming
 *   merchants), the 07 §2.9 shape.
 * - **Credit overspend** (`generateCreditOverspend`) — one credit-card
 *   charge far larger than the account's typical monthly activity, for a
 *   budgeting screen's cash/credit overspend split to have something real to
 *   render against.
 * - **Quiet-hours notification is deliberately not here.** It is a
 *   *timing* claim about when a notification is delivered relative to a
 *   user's configured quiet-hours window (`@ctx/notifications`'s own
 *   `quietHoursReleaseAt`, §4.3 of this WP's own evidence doc) — there is no
 *   corresponding *data* shape for `@core/seed` to produce: the generator
 *   has no concept of "when a sync happened" or "when a notification would
 *   have fired," only calendar history. `@ctx/notifications`'s own
 *   `test/db/quiet-hours.test.ts` already builds this scenario directly,
 *   correctly, at the layer that actually owns wall-clock timing — a
 *   ledger-seed fixture for it would either duplicate that harness's clock
 *   machinery or be decorative. Recorded here rather than silently omitted.
 */
import { DateOnly, Money } from '@core/kernel';
import { mulberry32, randomUuid, type Rng } from './prng.ts';
import type { AccountType, SeedAccount, SeedMerchant, SeedTransaction } from './types.ts';

type DateOnlyType = DateOnly;

function account(rng: Rng, type: AccountType, name: string, openedOn: DateOnlyType): SeedAccount {
  return { id: randomUuid(rng), type, name, currency: 'USD', openedOn, closedOn: null };
}

function merchant(rng: Rng, canonicalName: string, category: string): SeedMerchant {
  return { id: randomUuid(rng), canonicalName, category };
}

function txn(
  rng: Rng,
  input: {
    accountId: string;
    merchantId: string;
    amount: string;
    postedOn: DateOnlyType;
    descriptorRaw: string;
  },
): SeedTransaction {
  return {
    id: randomUuid(rng),
    accountId: input.accountId,
    merchantId: input.merchantId,
    kind: 'purchase',
    amount: Money.toJSON(Money.parseAmount(input.amount, 'USD')),
    pendingOn: null,
    postedOn: input.postedOn,
    status: 'posted',
    descriptorRaw: input.descriptorRaw,
  };
}

// ---------------------------------------------------------------------------
// Card migration
// ---------------------------------------------------------------------------

export interface CardMigrationScenario {
  readonly accounts: readonly [SeedAccount, SeedAccount]; // [before, after]
  readonly merchant: SeedMerchant;
  readonly transactions: readonly SeedTransaction[];
  readonly labels: {
    readonly fromAccountId: string;
    readonly toAccountId: string;
    /** The first date billed on `toAccountId`. */
    readonly migratedOn: DateOnlyType;
    readonly transactionIdsBeforeMigration: readonly string[];
    readonly transactionIdsAfterMigration: readonly string[];
  };
}

/**
 * One subscription, twelve monthly charges: six on a card that gets
 * reissued, then a one-period gap (the reissue itself), then six more on its
 * replacement. Deterministic from `seed`.
 */
export function generateCardMigration(
  seed: number,
  startMonth: DateOnlyType,
): CardMigrationScenario {
  const rng = mulberry32(seed * 2 + 1);
  const oldCard = account(
    rng,
    'credit_card',
    'Rewards Visa (old)',
    DateOnly.addMonths(startMonth, -12),
  );
  const newCard = account(
    rng,
    'credit_card',
    'Rewards Visa (reissued)',
    DateOnly.addMonths(startMonth, 5),
  );
  const streamingMerchant = merchant(rng, 'Planet Fitness', 'fitness');

  const before: SeedTransaction[] = [];
  for (let month = 0; month < 6; month += 1) {
    before.push(
      txn(rng, {
        accountId: oldCard.id,
        merchantId: streamingMerchant.id,
        amount: '-42.00',
        postedOn: DateOnly.of(
          DateOnly.year(DateOnly.addMonths(startMonth, month)),
          DateOnly.month(DateOnly.addMonths(startMonth, month)),
          9,
        ),
        descriptorRaw: 'PLANET FITNS #4471',
      }),
    );
  }
  // Month 6: the reissue itself — a skipped period, per 07 §2.2 ("propose the
  // merge *before* crying cancellation").
  const after: SeedTransaction[] = [];
  const migratedOn = DateOnly.of(
    DateOnly.year(DateOnly.addMonths(startMonth, 7)),
    DateOnly.month(DateOnly.addMonths(startMonth, 7)),
    9,
  );
  for (let month = 7; month < 13; month += 1) {
    after.push(
      txn(rng, {
        accountId: newCard.id,
        merchantId: streamingMerchant.id,
        amount: '-42.00',
        postedOn: DateOnly.of(
          DateOnly.year(DateOnly.addMonths(startMonth, month)),
          DateOnly.month(DateOnly.addMonths(startMonth, month)),
          9,
        ),
        descriptorRaw: 'PLANET FITNS #4471',
      }),
    );
  }

  return {
    accounts: [oldCard, newCard],
    merchant: streamingMerchant,
    transactions: [...before, ...after],
    labels: {
      fromAccountId: oldCard.id,
      toAccountId: newCard.id,
      migratedOn,
      transactionIdsBeforeMigration: before.map((t) => t.id),
      transactionIdsAfterMigration: after.map((t) => t.id),
    },
  };
}

// ---------------------------------------------------------------------------
// Duplicate service
// ---------------------------------------------------------------------------

export interface DuplicateServiceScenario {
  readonly account: SeedAccount;
  readonly merchants: readonly [SeedMerchant, SeedMerchant];
  readonly transactions: readonly SeedTransaction[];
  readonly labels: {
    readonly category: string;
    readonly merchantIds: readonly [string, string];
    /** 07 §2.9: the sum of all but the cheapest, annualised. */
    readonly cheaperMerchantId: string;
    readonly annualImpactMinor: string;
  };
}

/** Two concurrently active video-streaming subscriptions, six months each. */
export function generateDuplicateService(
  seed: number,
  startMonth: DateOnlyType,
): DuplicateServiceScenario {
  const rng = mulberry32(seed * 2 + 2);
  const card = account(rng, 'credit_card', 'Rewards Visa', DateOnly.addMonths(startMonth, -12));
  const streamA = merchant(rng, 'StreamFlix', 'entertainment.streaming');
  const streamB = merchant(rng, 'WatchPlus', 'entertainment.streaming');

  const transactions: SeedTransaction[] = [];
  for (let month = 0; month < 6; month += 1) {
    const postedOn = (day: number): DateOnlyType =>
      DateOnly.of(
        DateOnly.year(DateOnly.addMonths(startMonth, month)),
        DateOnly.month(DateOnly.addMonths(startMonth, month)),
        day,
      );
    transactions.push(
      txn(rng, {
        accountId: card.id,
        merchantId: streamA.id,
        amount: '-15.99',
        postedOn: postedOn(4),
        descriptorRaw: 'STREAMFLIX.COM',
      }),
      txn(rng, {
        accountId: card.id,
        merchantId: streamB.id,
        amount: '-11.99',
        postedOn: postedOn(17),
        descriptorRaw: 'WATCHPLUS SUBSCRIPTION',
      }),
    );
  }

  return {
    account: card,
    merchants: [streamA, streamB],
    transactions,
    labels: {
      category: 'entertainment.streaming',
      merchantIds: [streamA.id, streamB.id],
      // Keeping only the cheaper of the two frees the other's annual cost —
      // 07 §2.9's formula, computed by hand here for the caller to check.
      cheaperMerchantId: streamB.id,
      annualImpactMinor: '19188', // $15.99 x 12 = $191.88, in minor units
    },
  };
}

// ---------------------------------------------------------------------------
// Credit overspend
// ---------------------------------------------------------------------------

export interface CreditOverspendScenario {
  readonly account: SeedAccount;
  readonly merchant: SeedMerchant;
  /** Six months of ordinary spending, then one outsized charge. */
  readonly transactions: readonly SeedTransaction[];
  readonly labels: {
    readonly overspendTransactionId: string;
    readonly typicalMonthlyMinor: string;
    readonly overspendMinor: string;
  };
}

/**
 * A credit card with six months of ordinary ~$300/mo dining activity, then
 * one $1,800 charge far outside that pattern — big enough that no plausible
 * monthly budget envelope could have covered it in cash, so `07 §1.3`'s
 * credit-overspend split has something real to compute against.
 */
export function generateCreditOverspend(
  seed: number,
  startMonth: DateOnlyType,
): CreditOverspendScenario {
  const rng = mulberry32(seed * 2 + 3);
  const card = account(rng, 'credit_card', 'Rewards Visa', DateOnly.addMonths(startMonth, -12));
  const diningMerchant = merchant(rng, 'The Corner Bistro', 'dining.restaurants');

  const ordinary: SeedTransaction[] = [];
  for (let month = 0; month < 6; month += 1) {
    ordinary.push(
      txn(rng, {
        accountId: card.id,
        merchantId: diningMerchant.id,
        amount: '-300.00',
        postedOn: DateOnly.of(
          DateOnly.year(DateOnly.addMonths(startMonth, month)),
          DateOnly.month(DateOnly.addMonths(startMonth, month)),
          14,
        ),
        descriptorRaw: 'CORNER BISTRO',
      }),
    );
  }
  const overspend = txn(rng, {
    accountId: card.id,
    merchantId: diningMerchant.id,
    amount: '-1800.00',
    postedOn: DateOnly.of(
      DateOnly.year(DateOnly.addMonths(startMonth, 6)),
      DateOnly.month(DateOnly.addMonths(startMonth, 6)),
      14,
    ),
    descriptorRaw: 'CORNER BISTRO EVENT',
  });

  return {
    account: card,
    merchant: diningMerchant,
    transactions: [...ordinary, overspend],
    labels: {
      overspendTransactionId: overspend.id,
      typicalMonthlyMinor: '30000',
      overspendMinor: '180000',
    },
  };
}
