/**
 * WP 3.14 — the investments half of the demo seed, **with ground truth**.
 *
 * ## Why this is a separate generator and not more of `generateDemoData`
 *
 * The same reason `phase2-scenarios.ts` is separate, stated again because it is
 * the thing that would break if someone folded this in: `generateDemoData`'s
 * output is *pinned* — `@ctx/categorization`'s golden accuracy set and
 * `@ctx/recurring`'s corpora are graded against it, and every id and every
 * amount downstream of a new `rng` draw moves if the draw order changes.
 * Adding six accounts and fourteen investment transactions to the household
 * generator would have re-rolled two phases' golden numbers to add a fixture.
 * So this is additive: a caller loads it **on top of** (never instead of) the
 * pinned household.
 *
 * ## What "ground truth" means here, and why it is hand-computed
 *
 * The generator **declares** what the basis engine must conclude: every lot's
 * basis, its `quantity_remaining` after the disposals below, the short-term /
 * long-term split of every realised gain, and every `POSSIBLE_WASH_SALE` —
 * including the one that must **not** be flagged, at day 31. Those numbers are
 * literals, worked out by hand (the arithmetic is written beside each one and
 * again in `docs/evidence/phase-3/wp3.14-quality.md` §3), **not** computed by
 * calling the engine they are used to grade. A fixture generated by the code
 * under test asserts only that the code is self-consistent — the same rule WP
 * 3.3's spreadsheet fixture states for allocation.
 *
 * `packages/seed/test/investments-ground-truth.test.ts` drives
 * `@ctx/investments`' pure engine over the transactions below and compares.
 *
 * ## Deliberate contents
 *
 * Every entry here exists because something downstream has to be forced to
 * face it:
 *
 *   * **a lot with an unknown basis** (`L9`, a transfer in) — unrealised gain
 *     must be `unavailable`, never gain-from-zero (04 §5.5);
 *   * **a wash sale at day 16** and **a repurchase at day 31 that is not one** —
 *     the 61-day window's far boundary, in an IRA, where Rev. Rul. 2008-5
 *     would make the adjustment permanent if it did apply;
 *   * **an 18-decimal crypto quantity** disposed of across a lot boundary;
 *   * **a non-USD (CAD) account** and **an FX series with exactly one gap** —
 *     a missing rate must surface, never default to 1.0 (D4);
 *   * **a manual asset and a liability** — the §5 net-worth exit criterion says
 *     "every account type including a manual asset and a liability";
 *   * **a cash position**, which belongs in the allocation denominator.
 *
 * Money is `MoneyJson` (minor units as a *string*) and quantities and prices
 * are decimal strings, for the reason `types.ts` gives: this has to survive
 * `JSON.stringify` byte for byte, and a `bigint` cannot. No value in this file
 * is ever an IEEE-754 double — see `scripts/check-numeric-boundaries.ts`.
 */
