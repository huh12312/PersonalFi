// ---------------------------------------------------------------------------
// The price and FX walks
// ---------------------------------------------------------------------------

const BPS = 10_000n;

interface WalkSpec {
  /** Where the walk starts, in the smallest unit of `scale`. */
  readonly openMinor: bigint;
  readonly volatilityBps: number;
  readonly driftBps: number;
  readonly scale: number;
}

/**
 * A month-end series that **ends on a pinned value**.
 *
 * The walk gives the history its shape; the last point is the literal the
 * ground truth is computed from, so "quantity × the last close = the declared
 * market value" is an assertion about the engine's rounding rather than about
 * a random walk that happened to land somewhere. Integer arithmetic
 * throughout: a price never becomes a double (08 §6.5).
 */
function walkTo(
  rng: Rng,
  spec: WalkSpec,
  dates: readonly DateOnlyType[],
  closeOnLast: string,
): string[] {
  const out: string[] = [];
  let current = spec.openMinor;
  for (let index = 0; index < dates.length; index += 1) {
    if (index === dates.length - 1) {
      out.push(closeOnLast);
      break;
    }
    const shockBps = randomInt(rng, -spec.volatilityBps, spec.volatilityBps);
    current = current + (current * BigInt(spec.driftBps + shockBps)) / BPS;
    if (current < 1n) current = 1n;
    out.push(formatScaledInteger(current, spec.scale));
  }
  return out;
}

function monthEnds(startMonth: DateOnlyType, monthCount: number): DateOnlyType[] {
  const dates: DateOnlyType[] = [];
  for (let offset = 0; offset < monthCount; offset += 1) {
    dates.push(DateOnly.endOfMonth(DateOnly.addMonths(startMonth, offset)));
  }
  return dates;
}

