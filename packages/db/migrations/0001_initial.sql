-- Forward-only. Once merged, this file is immutable: the runner records a
-- SHA-256 of its contents and refuses to start if it ever changes.
--
-- Conventions asserted here and inherited by every later migration:
--   * primary keys are UUIDv7 generated app-side (newId()), never gen_random_uuid()
--   * every user-scoped table carries user_id (decision D6)
--   * instants are timestamptz; business dates are date
--   * money is BIGINT minor units paired with CHAR(3) ISO-4217; quantities are NUMERIC(38,18)

-- Bookkeeping. Created by the runner too, so a fresh database can bootstrap; kept
-- here so the schema is fully described by the migrations alone.
CREATE TABLE IF NOT EXISTS schema_migrations (
  version      TEXT        PRIMARY KEY,
  name         TEXT        NOT NULL,
  checksum     TEXT        NOT NULL,
  applied_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  execution_ms INTEGER     NOT NULL
);

COMMENT ON TABLE schema_migrations IS 'Applied migrations. Owner: @core/db.';

-- Owner: @ctx/identity.
CREATE TABLE users (
  id           UUID        PRIMARY KEY,
  display_name TEXT        NOT NULL CHECK (length(btrim(display_name)) > 0),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE users IS 'The account holder. Single user today; multi-user is additive. Owner: @ctx/identity.';
COMMENT ON COLUMN users.id IS 'UUIDv7, generated by the application before INSERT.';

-- Owner: @core/db (platform).
CREATE TABLE feature_flags (
  user_id    UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  key        TEXT        NOT NULL CHECK (key ~ '^[a-z0-9]+(\.[a-z0-9_-]+)*$'),
  enabled    BOOLEAN     NOT NULL DEFAULT false,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, key)
);

COMMENT ON TABLE feature_flags IS
  'Per-user overrides for progressive module rollout. Defaults live in code; a row here overrides one. Owner: @core/db.';
COMMENT ON COLUMN feature_flags.key IS 'Dotted key, e.g. module.investments or advisor.builtin.';
