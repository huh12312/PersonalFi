/**
 * Holdings reconcile to balances — the v0.5 rung clause
 * (docs/evidence/phase-3/wp3.14-quality.md §1, §8 item 5) that had no test
 * anywhere in the tree before this file: `holdings.institution_value_minor`
 * was written and never compared to `quantity × price`.
 *
 * `../src/reconcile.ts` carries the full design rationale and the tolerance
 * rule in its header; the summary that matters for reading these fixtures:
 * **one minor unit of disagreement is `reconciled`** (two independent, honest
 * roundings of the same real number can differ by exactly that much),
 * **anything larger is `tolerance_breach`**, and **no price at all is
 * `no_price`**, never a silent pass folded into either of the other two.
 *
 * `@core/seed`'s Phase 3 ground truth is not imported here: this package has
 * no `investments` entry in `scripts/eslint-boundaries.js`'s `LAYERS`, so it
 * falls under the generic `context` layer, whose allow-list has no
 * `@core/seed` (see `test/db/harness.ts`'s header for the same constraint on
 * `@core/testkit`). Every fixture below is therefore hand-built, with its
 * arithmetic written out beside it, the same rule
 * `packages/seed/test/investments-ground-truth.test.ts`'s own header states
 * for a fixture generated by the code under test.
 */
import { DateOnly, Money, Quantity, currency } from '@core/kernel';
import { describe, expect, it } from 'vitest';
import type { Holding } from '../src/holdings.ts';
import type { LotPrice } from '../src/basis.ts';
import {
  DEFAULT_RECONCILE_TOLERANCE_MINOR,
  reconcileHolding,
  reconcileHoldings,
  type HoldingReconciliation,
} from '../src/reconcile.ts';

const USD = currency('USD');
const CAD = currency('CAD');
const ACCOUNT = 'acct-brokerage';
const AS_OF = DateOnly.parse('2026-09-24');

const usd = (minor: bigint): ReturnType<typeof Money.of> => Money.of(minor, USD);
const price = (amount: string, code = USD): LotPrice => ({
  amount: Quantity.of(amount),
  currency: code,
});

function holding(securityId: string, quantity: string, institutionValueMinor: bigint): Holding {
  return {
    accountId: ACCOUNT,
    securityId,
    quantity: Quantity.of(quantity),
    institutionValue: usd(institutionValueMinor),
    costBasis: null,
    asOfDate: AS_OF,
  };
}

describe('holdings reconcile to balances', () => {
  it('holdings reconcile to balances', () => {
    // VTI: 10 x $305.12 = $3,051.20 exactly. The institution says the same
    // number, so this is a plain, exact `reconciled`.
    const vti = holding('sec-vti', '10', 305_120n);
    const vtiPrice = price('305.12');

    // BND: 5 x $71.50 = $357.50 -> 35750 minor. The institution says 35751 —
    // one minor unit higher, exactly `DEFAULT_RECONCILE_TOLERANCE_MINOR`, so
    // this is the boundary case and it is still `reconciled`.
    const bnd = holding('sec-bnd', '5', 35_751n);
    const bndPrice = price('71.50');

    // AAPL: 20 x $245.00 = $4,900.00 -> 490000 minor. The institution says
    // 490150 — 150 minor units off, far past rounding, so `tolerance_breach`.
    const aapl = holding('sec-aapl', '20', 490_150n);
    const aaplPrice = price('245.00');

    // VXUS: no price available at all (a fresh install, a delisted fund, a
    // provider outage) — `no_price`, never folded into either other state.
    const vxus = holding('sec-vxus', '5', 32_100n);

    const priceOf = (h: Holding): LotPrice | null =>
      h.securityId === 'sec-vti'
        ? vtiPrice
        : h.securityId === 'sec-bnd'
          ? bndPrice
          : h.securityId === 'sec-aapl'
            ? aaplPrice
            : null;

    const results = reconcileHoldings([vti, bnd, aapl, vxus], priceOf, () => 2);

    expect(results).toEqual<readonly HoldingReconciliation[]>([
      {
        accountId: ACCOUNT,
        securityId: 'sec-vti',
        status: 'reconciled',
        institutionValue: usd(305_120n),
        computedValue: usd(305_120n),
        differenceMinor: 0n,
      },
      {
        accountId: ACCOUNT,
        securityId: 'sec-bnd',
        status: 'reconciled',
        institutionValue: usd(35_751n),
        computedValue: usd(35_750n),
        differenceMinor: -1n,
      },
      {
        accountId: ACCOUNT,
        securityId: 'sec-aapl',
        status: 'tolerance_breach',
        institutionValue: usd(490_150n),
        computedValue: usd(490_000n),
        differenceMinor: -150n,
      },
      {
        accountId: ACCOUNT,
        securityId: 'sec-vxus',
        status: 'no_price',
        institutionValue: usd(32_100n),
        computedValue: null,
        differenceMinor: null,
      },
    ]);
  });

  it('a difference of exactly one minor unit is reconciled; two is a tolerance_breach', () => {
    // Isolates the boundary from the composite test above: same holding, same
    // price, only the institution's number moves.
    const base = holding('sec-boundary', '100', 500_000n); // 100 x $50.00 = $5,000.00
    const atTwo = holding('sec-boundary', '100', 500_002n);
    const p = price('50.00');

    expect(reconcileHolding(base, p, 2).status).toBe('reconciled');
    expect(reconcileHolding(atTwo, p, 2).status).toBe('tolerance_breach');
    expect(DEFAULT_RECONCILE_TOLERANCE_MINOR).toBe(1n);
  });

  it('an 18-decimal crypto quantity reconciles exactly, with no float in the path', () => {
    // 1.5 ETH x $3,150.00 = $4,725.00 -> 472500 minor, with a quantity string
    // shaped the way the schema's NUMERIC(38,18) column actually stores one.
    const eth = holding('sec-eth', '1.500000000000000000', 472_500n);
    const result = reconcileHolding(eth, price('3150.00'), 2);
    expect(result).toEqual({
      accountId: ACCOUNT,
      securityId: 'sec-eth',
      status: 'reconciled',
      institutionValue: usd(472_500n),
      computedValue: usd(472_500n),
      differenceMinor: 0n,
    });
  });

  it('never coerces a currency mismatch between the holding and the price', () => {
    const cadPriceForUsdHolding = holding('sec-mismatch', '10', 100_000n);
    expect(() => reconcileHolding(cadPriceForUsdHolding, price('10.00', CAD), 2)).toThrow(
      /never coerces a currency/,
    );
  });
});
