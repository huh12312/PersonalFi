/**
 * The spreadsheet check — the Phase 3 §5 exit criterion (*"allocation matches
 * a spreadsheet check"*) and the v0.5 rung.
 *
 * There was no committed spreadsheet before this work package, so one was
 * authored: `test/fixtures/allocation-portfolio.csv` holds the positions with
 * the formulas a spreadsheet would use written at the top of the file, and
 * `test/fixtures/allocation-expected.csv` holds every expected slice value and
 * weight. **The expectations were computed with an independent decimal
 * implementation, not with the engine they pin** — see
 * `docs/evidence/phase-3/wp3.3-analytics.md` §4 for the transcript. A fixture
 * generated by the code under test asserts only that the code is
 * self-consistent.
 *
 * The portfolio is chosen to carry the failure modes, not to look tidy: a
 * fractional crypto quantity, a cash position that must be in the denominator,
 * an `UNCLASSIFIED` holding, one `STALE` price, one security in two accounts,
 * and two holdings with no expense ratio.
 */
import { Money, currency } from '@core/kernel';
import { describe, expect, it } from 'vitest';
import { FIXTURE_HOLDINGS, expectedSlices, expectedTotal } from '../../test/fixtures/portfolio.ts';
import {
  allocationBy,
  allocationByAssetClass,
  totalWeightOf,
  valueHoldings,
  type AllocationDimension,
} from './allocation.ts';
import {
  portfolioDollarGain,
  ratio,
  type AnalyticsHolding,
  type ValuationOptions,
} from './types.ts';

const USD = currency('USD');
const SCALE = 2;

const AS_OF_NOW: ValuationOptions = { currency: USD, scale: SCALE, basis: 'as_of_now' };
const LAST_KNOWN: ValuationOptions = { currency: USD, scale: SCALE, basis: 'last_known' };

describe('allocation', () => {
  it('allocation matches the committed spreadsheet fixture to the cent', () => {
    for (const basis of ['last_known', 'as_of_now'] as const) {
      const options: ValuationOptions = basis === 'as_of_now' ? AS_OF_NOW : LAST_KNOWN;
      const set = valueHoldings(FIXTURE_HOLDINGS, options);

      // Every holding's value, to the cent, against the spreadsheet column.
      for (const entry of set.valued) {
        const fixture = FIXTURE_HOLDINGS.find((row) => row.holdingId === entry.holding.holdingId);
        expect(Money.formatAmount(entry.marketValue)).toBe(fixture?.expectedMarketValue);
      }

      // The denominator, to the cent.
      expect(Money.formatAmount(set.total)).toBe(expectedTotal(basis));

      // And every slice of every dimension, value and weight.
      for (const dimension of ['asset_class', 'region', 'sector'] as const) {
        const report = allocationBy(
          dimension satisfies AllocationDimension,
          FIXTURE_HOLDINGS,
          options,
        );
        const expected = expectedSlices(basis, dimension);
        expect(report.slices.map((slice) => slice.key)).toEqual(expected.map((row) => row['key']));
        for (const row of expected) {
          const slice = report.slices.find((candidate) => candidate.key === row['key']);
          expect(Money.formatAmount(slice?.value ?? Money.zero(USD))).toBe(row['expected_value']);
          expect(slice?.weight).toBe(row['expected_weight']);
        }
        // The weights account for the whole portfolio, not merely most of it.
        // Each weight is rounded to the ratio scale independently, so the sum
        // can land one ulp of that scale away from 1 per slice — 1e-10 × slices,
        // which is 1e-8 of a percentage point and is stated rather than hidden.
        expect(Math.abs(Number(totalWeightOf(report)) - 1)).toBeLessThanOrEqual(
          report.slices.length * 1e-10,
        );
      }
    }
  });

  it('keeps cash in the denominator, which is what the fixture pins', () => {
    // The sabotage in the evidence note drops cash-equivalent holdings from
    // `valueHoldings`. This is the arithmetic that catches it: without the
    // $12,500 sweep balance the total falls and every other weight inflates.
    const withCash = allocationByAssetClass(FIXTURE_HOLDINGS, LAST_KNOWN);
    const withoutCash = allocationByAssetClass(
      FIXTURE_HOLDINGS.filter((holding) => !holding.isCashEquivalent),
      LAST_KNOWN,
    );

    expect(Money.formatAmount(withCash.total)).toBe('176499.60');
    expect(Money.formatAmount(withoutCash.total)).toBe('163999.60');
    expect(withCash.includesCash).toBe(true);

    const equityWith = withCash.slices.find((slice) => slice.key === 'US_EQUITY')?.weight;
    const equityWithout = withoutCash.slices.find((slice) => slice.key === 'US_EQUITY')?.weight;
    expect(equityWith).toBe('0.4323001299');
    expect(equityWithout).toBe('0.4652499152');
    // 3.3 points of pure artefact — more than half the 5-point drift band.
    expect(Number(equityWithout) - Number(equityWith)).toBeGreaterThan(0.03);
  });

  it('unclassifiedPct is returned whenever any holding is UNCLASSIFIED', () => {
    const report = allocationByAssetClass(FIXTURE_HOLDINGS, LAST_KNOWN);
    expect(report.unclassifiedPct).toBe('0.0174504645');
    expect(Money.formatAmount(report.unclassifiedValue)).toBe('3080.00');

    // Region and sector have their own name for the same idea, and it is
    // reported in the same field rather than left to the caller to find.
    expect(allocationBy('region', FIXTURE_HOLDINGS, LAST_KNOWN).unclassifiedPct).toBe(
      '0.0174504645',
    );
    expect(allocationBy('sector', FIXTURE_HOLDINGS, LAST_KNOWN).unclassifiedPct).toBe(
      '0.2008537130',
    );

    // And it is present — as an explicit zero — when nothing is unclassified,
    // so a UI never has to distinguish "absent" from "none".
    const classified = allocationByAssetClass(
      FIXTURE_HOLDINGS.filter((holding) => holding.assetClass !== 'UNCLASSIFIED'),
      LAST_KNOWN,
    );
    expect(classified.unclassifiedPct).toBe(ratio('0'));
    expect(classified).toHaveProperty('unclassifiedPct');
  });

  it('a STALE price is excluded from an as-of-now allocation', () => {
    const asOfNow = allocationByAssetClass(FIXTURE_HOLDINGS, AS_OF_NOW);
    const lastKnown = allocationByAssetClass(FIXTURE_HOLDINGS, LAST_KNOWN);

    // Out of the numerator *and* the denominator — not counted at a stale
    // price, and not coerced to zero either, which would be the same lie.
    expect(Money.formatAmount(asOfNow.total)).toBe('174449.60');
    expect(Money.formatAmount(lastKnown.total)).toBe('176499.60');
    expect(Money.subtract(lastKnown.total, asOfNow.total)).toEqual(
      Money.parseAmount('2050.00', USD),
    );

    // And it is named, so the UI can say which position is stale.
    expect(asOfNow.excluded).toEqual([
      { holdingId: 'h-10', symbol: 'OLDCO', reason: 'stale_price' },
    ]);
    expect(lastKnown.excluded).toEqual([]);

    // The stale holding's own weight is absent rather than zero.
    const asOfNowIds = asOfNow.slices.flatMap((slice) => slice.holdingIds);
    expect(asOfNowIds).not.toContain('h-10');
    expect(lastKnown.slices.flatMap((slice) => slice.holdingIds)).toContain('h-10');
  });

  it('excludes an unpriced holding rather than valuing it at zero', () => {
    const unpriced: AnalyticsHolding = {
      ...(FIXTURE_HOLDINGS[0] as AnalyticsHolding),
      holdingId: 'h-99',
      price: null,
    };
    const set = valueHoldings([...FIXTURE_HOLDINGS, unpriced], LAST_KNOWN);
    expect(set.excluded).toContainEqual({
      holdingId: 'h-99',
      symbol: 'VTI',
      reason: 'price_unknown',
    });
    expect(Money.formatAmount(set.total)).toBe('176499.60');
  });

  it('carries the fixture’s missing cost basis through to an unavailable gain', () => {
    const set = valueHoldings(FIXTURE_HOLDINGS, LAST_KNOWN);
    const gain = portfolioDollarGain(
      set.valued.map((entry) => ({
        id: entry.holding.holdingId,
        marketValue: entry.marketValue,
        costBasis: entry.holding.costBasis,
      })),
      USD,
    );
    // The BTC position has no basis, so the portfolio gain is unavailable —
    // it is not $19,870.60 of invented profit, and not a partial total either.
    expect(gain.status).toBe('unavailable');
    if (gain.status !== 'unavailable') throw new Error('unreachable');
    expect(gain.reason).toBe('basis_unknown');
    expect(gain.positionIds).toEqual(['h-06']);
    expect(Money.formatAmount(gain.marketValue ?? Money.zero(USD))).toBe('176499.60');
  });
});
