const BY_CODE: ReadonlyMap<string, MccCode> = new Map(MCC_CODES.map((row) => [row.mcc, row]));

/**
 * Look up a code, tolerating the two ways a four-digit code arrives as three.
 *
 * `'742'` and `'0742'` are the same MCC; a CSV that dropped the leading zero is
 * common enough that failing to pad here would silently lose every veterinary
 * charge in the file.
 */
export function lookupMcc(raw: string | number | null | undefined): MccCode | undefined {
  if (raw === null || raw === undefined) return undefined;
  const digits = String(raw).trim();
  if (!/^\d{1,4}$/u.test(digits)) return undefined;
  return BY_CODE.get(digits.padStart(4, '0'));
}

/** Every category key this table can produce. Used by the coverage test. */
export function mccCategoryKeys(): ReadonlySet<string> {
  return new Set(MCC_CODES.map((row) => row.categoryKey));
}

/** True when every row points at a leaf the engine is allowed to assign. */
export function mccTableIsWellFormed(): boolean {
  return MCC_CODES.every((row) => isAssignableKey(row.categoryKey));
}
