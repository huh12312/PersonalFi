/**
 * Merchant Category Codes (ISO 18245), and what each one means to us.
 *
 * ## Provenance
 *
 * The code list and the `description` strings are `greggles/mcc-codes`
 * (`mcc_codes.csv`, the `edited_description` column), which is released into the
 * public domain under **the Unlicense** — verified against the GitHub licensing
 * API on 2026-09-13, and the verdict 02 §4.4 already recorded ("ship verbatim").
 * That is why this is the one dataset in the repo copied word for word: there is
 * no licence to honour and no attribution to carry, though `THIRD_PARTY.md`
 * records it anyway because a reader deserves to know where 981 strings came
 * from. Note what is *not* from there — `python-iso18245` bundles Visa/MC/Amex
 * descriptions whose provenance 02 §4.4 flagged as unverified, so none of its
 * text is here.
 *
 * The third column is entirely ours: which of *our* taxonomy leaves a code means.
 * It is produced by `MCC_RANGES` plus `MCC_EXACT` below rather than hand-filed
 * per row, because three ranges (airlines, car rental, lodging) account for 683
 * of the 981 codes and writing those out individually would bury the ~300 that
 * carry real information.
 *
 * ## What this tier is actually for
 *
 * MCC is the *last* structural signal before guessing. Plaid does not ship it on
 * `/transactions/sync`, so today it reaches us only from a CSV or OFX import that
 * carries one — which is exactly the case where `personal_finance_category` is
 * absent and the classifier has the least to go on. It is wired as a feature of
 * the classifier tier rather than as a tier of its own: an MCC is a statement
 * about how a merchant registered with its acquirer, not about what the user
 * bought, and "registered as a superstore" is a weaker claim than "the last four
 * transactions here were groceries".
 *
 * `mcc.test.ts` asserts every one of the 981 codes resolves to an assignable
 * leaf. There is deliberately **no catch-all range**: a fallback to
 * `uncategorised` would make that test pass while proving nothing.
 */

