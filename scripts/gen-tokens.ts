/**
 * `node scripts/gen-tokens.ts` — the design-token generator (WP 10.8).
 *
 * One source, three outputs, so CSS and TypeScript cannot drift:
 *
 *   source  apps/web/src/styles/tokens/radix-colors.ts   the vendored Radix Colors scales (MIT), pinned
 *           apps/web/src/styles/tokens/roles.ts          the semantic roles, each a scale step (or a named
 *                                                        off-scale house value, with the reason)
 *   output  apps/web/src/styles/tokens.css               the scales + roles + legacy aliases as CSS custom
 *                                                        properties, light / dark / system-dark
 *           apps/web/src/styles/tokens.ts                the same values as a typed object for canvas/SVG code
 *
 * `src/styles/tokens.test.ts` regenerates both in memory and fails on any byte of difference, and also parses
 * the CSS back and compares it to the TS object.
 *
 * Modes:
 *   node scripts/gen-tokens.ts                     write tokens.css and tokens.ts
 *   node scripts/gen-tokens.ts --check             exit 1 if either checked-in file differs from a regeneration
 *   node scripts/gen-tokens.ts --refresh-radix DIR re-vendor radix-colors.ts from an *unpacked* @radix-ui/colors
 *                                                  package directory (reads its `<scale>.css` / `<scale>-dark.css`
 *                                                  as text; nothing from the package is executed or imported)
 *
 * Why vendored rather than a devDependency: `@radix-ui/colors` is not in the lockfile, and this WP may not change
 * it. The pinned version and the tarball's registry integrity are recorded in `radix-colors.ts`; the MIT notice
 * is reproduced there and in THIRD_PARTY.md (via `scripts/check-licenses.ts`' preamble).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { RADIX_SCALE_NAMES } from '../apps/web/src/styles/tokens/scale-names.ts';

const ROOT = resolve(import.meta.dirname, '..');
const STYLES = join(ROOT, 'apps/web/src/styles');

/** Loaded lazily: `--refresh-radix` must run before the vendored scales (which `generate.ts` reads) exist. */
async function outputs(): Promise<ReadonlyArray<readonly [string, () => string]>> {
  const { renderCss, renderTs } = await import('../apps/web/src/styles/tokens/generate.ts');
  return [
    [join(STYLES, 'tokens.css'), renderCss],
    [join(STYLES, 'tokens.ts'), renderTs],
  ];
}

function refreshRadix(dir: string): void {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as {
    name: string;
    version: string;
  };
  if (pkg.name !== '@radix-ui/colors') throw new Error(`${dir} is not @radix-ui/colors`);
  const license = readFileSync(join(dir, 'LICENSE'), 'utf8').trim();
  const read = (file: string, scale: string): string[] => {
    const text = readFileSync(join(dir, file), 'utf8');
    // The first block of each file is the sRGB one; the P3 block follows under @supports.
    const steps: string[] = [];
    for (let step = 1; step <= 12; step += 1) {
      const match = new RegExp(`--${scale}-${String(step)}:\\s*(#[0-9a-f]{6})\\s*;`, 'i').exec(
        text,
      );
      if (match?.[1] === undefined)
        throw new Error(`${file}: no sRGB hex for --${scale}-${String(step)}`);
      steps.push(match[1].toLowerCase());
    }
    return steps;
  };
  const lines: string[] = [];
  for (const scale of RADIX_SCALE_NAMES) {
    const light = read(`${scale}.css`, scale);
    const dark = read(`${scale}-dark.css`, scale);
    lines.push(
      `  ${scale}: {`,
      `    light: [${light.map((h) => `'${h}'`).join(', ')}],`,
      `    dark: [${dark.map((h) => `'${h}'`).join(', ')}],`,
      `  },`,
    );
  }
  const body = [
    '// SPDX-License-Identifier: MIT',
    '//',
    `// GENERATED by \`node scripts/gen-tokens.ts --refresh-radix <dir>\` from ${pkg.name}@${pkg.version}`,
    '// (https://registry.npmjs.org/@radix-ui/colors/-/colors-3.0.0.tgz, registry integrity',
    '// sha512-FUOsGBkHrYJwCSEtWRCIfQbZG7q1e6DgxCIOe1SUQzDe/7rXXeA47s8yCn6fuTNQAj1Zq4oTFi9Yjp3wzElcxg==).',
    '// The sRGB values of each scale, steps 1-12, light and dark. Do not edit by hand.',
    '//',
    ...license.split('\n').map((line) => (line === '' ? '//' : `// ${line}`)),
    '',
    `export const RADIX_COLORS_VERSION = '${pkg.version}';`,
    '',
    'export const RADIX_SCALES = {',
    ...lines,
    '} as const;',
    '',
  ].join('\n');
  writeFileSync(join(STYLES, 'tokens/radix-colors.ts'), body);
  console.log(
    `radix-colors.ts: ${String(RADIX_SCALE_NAMES.length)} scales from ${pkg.name}@${pkg.version}`,
  );
}

const args = process.argv.slice(2);
if (args[0] === '--refresh-radix') {
  const dir = args[1];
  if (dir === undefined) throw new Error('--refresh-radix needs the unpacked package directory');
  refreshRadix(resolve(dir));
} else if (args[0] === '--check') {
  const stale = (await outputs())
    .filter(([file, render]) => readFileSync(file, 'utf8') !== render())
    .map(([file]) => file);
  if (stale.length > 0) {
    console.error(`stale (run node scripts/gen-tokens.ts): ${stale.join(', ')}`);
    process.exit(1);
  }
  console.log('tokens.css and tokens.ts match their source');
} else {
  for (const [file, render] of await outputs()) writeFileSync(file, render());
  console.log('wrote tokens.css and tokens.ts');
}
