/**
 * Pure renderers for `scripts/gen-tokens.ts` (WP 10.8): the role source (`roles.ts`) and the vendored scales
 * (`radix-colors.ts`) → the text of `src/styles/tokens.css` and `src/styles/tokens.ts`. No I/O here, so
 * `tokens.test.ts` can regenerate in memory and compare byte for byte.
 */
import { RADIX_COLORS_VERSION, RADIX_SCALES } from './radix-colors.ts';
import { ALIASES, ROLE_GROUPS, type RoleDef } from './roles.ts';
import { RADIX_SCALE_NAMES } from './scale-names.ts';

export type ThemeName = 'light' | 'dark';
export const THEME_NAMES: readonly ThemeName[] = ['light', 'dark'];

const STEP_REF = /^([a-z]+)-(\d{1,2})$/;

/** `'sand-2'` → its hex in `theme`; `null` when `ref` is not a scale step (an off-scale house value). */
export function scaleStep(ref: string, theme: ThemeName): string | null {
  const match = STEP_REF.exec(ref);
  if (match === null) return null;
  const scale = RADIX_SCALES[match[1] as keyof typeof RADIX_SCALES] as
    { light: readonly string[]; dark: readonly string[] } | undefined;
  const step = Number(match[2]);
  if (scale === undefined || step < 1 || step > 12) throw new Error(`unknown scale step ${ref}`);
  return scale[theme][step - 1] as string;
}

export function resolveRef(ref: string): (theme: ThemeName) => string {
  return (theme) => scaleStep(ref, theme) ?? ref;
}

export interface ResolvedToken {
  readonly name: `--${string}`;
  readonly group: string;
  readonly ref: Readonly<Record<ThemeName, string>>;
  readonly value: Readonly<Record<ThemeName, string>>;
  /** `null` for a scale step / alias; the reason for an off-scale value. */
  readonly why: string | null;
  readonly aliasOf: `--${string}` | null;
}

function resolveRole(name: `--${string}`, group: string, def: RoleDef): ResolvedToken {
  const value = {
    light: scaleStep(def.light, 'light') ?? def.light,
    dark: scaleStep(def.dark, 'dark') ?? def.dark,
  };
  return {
    name,
    group,
    ref: { light: def.light, dark: def.dark },
    value,
    why: def.why ?? null,
    aliasOf: null,
  };
}

/** Every token, in output order: the scales, each role group, then the legacy aliases. */
export function resolveAll(): ResolvedToken[] {
  const out: ResolvedToken[] = [];
  for (const scale of RADIX_SCALE_NAMES) {
    for (let step = 1; step <= 12; step += 1) {
      const ref = `${scale}-${String(step)}`;
      out.push(resolveRole(`--${ref}`, `Radix Colors ${scale}`, { light: ref, dark: ref }));
    }
  }
  const roles = new Map<string, ResolvedToken>();
  for (const group of ROLE_GROUPS) {
    for (const [name, def] of Object.entries(group.roles) as Array<[`--${string}`, RoleDef]>) {
      if (roles.has(name)) throw new Error(`${name} is declared twice`);
      const token = resolveRole(name, group.title, def);
      roles.set(name, token);
      out.push(token);
    }
  }
  for (const [legacy, role] of Object.entries(ALIASES) as Array<[`--${string}`, `--${string}`]>) {
    const target = roles.get(role);
    if (target === undefined) throw new Error(`alias ${legacy} → ${role}: no such role`);
    if (roles.has(legacy)) throw new Error(`alias ${legacy} shadows a role`);
    out.push({
      ...target,
      name: legacy,
      group: 'Legacy names (read the role named beside each)',
      why: null,
      aliasOf: role,
    });
  }
  return out;
}

function comment(token: ResolvedToken, theme: ThemeName): string {
  if (token.aliasOf !== null) return ` /* = ${token.aliasOf} */`;
  if (token.group.startsWith('Radix')) return '';
  const ref = token.ref[theme];
  return STEP_REF.test(ref) ? ` /* ${ref} */` : ' /* house */';
}

function block(
  selector: string,
  theme: ThemeName,
  tokens: readonly ResolvedToken[],
  indent: string,
): string[] {
  const lines = [`${indent}${selector} {`, `${indent}  color-scheme: ${theme};`];
  let group = '';
  for (const token of tokens) {
    if (token.group !== group) {
      group = token.group;
      lines.push('', `${indent}  /* ${group} */`);
    }
    lines.push(`${indent}  ${token.name}: ${token.value[theme]};${comment(token, theme)}`);
  }
  lines.push(`${indent}}`);
  return lines;
}

const HEADER = [
  '/* SPDX-License-Identifier: MIT */',
  '',
  '/*',
  ' * GENERATED by `node scripts/gen-tokens.ts` from src/styles/tokens/{roles,fills,radix-colors}.ts.',
  ' * Do not edit: change the source and regenerate (tokens.test.ts fails on any drift).',
  ' *',
  ` * Scales: Radix Colors ${RADIX_COLORS_VERSION} (https://github.com/radix-ui/colors), MIT License,`,
  ' * Copyright (c) 2021 Radix — the full notice is in src/styles/tokens/radix-colors.ts and THIRD_PARTY.md.',
  ' *',
  ' * Three blocks, one palette each: light (`:root` and any `[data-theme="light"]` subtree), dark',
  " * (`[data-theme='dark']`), and the system-dark default before the user picks (the same values as dark).",
  ' * Every value is a literal so a nested `data-theme` subtree repaints without a var() chain.',
  ' */',
];

export function renderCss(): string {
  const tokens = resolveAll();
  return [
    ...HEADER,
    '',
    ...block(":root,\n[data-theme='light']", 'light', tokens, ''),
    '',
    ...block("[data-theme='dark']", 'dark', tokens, ''),
    '',
    '@media (prefers-color-scheme: dark) {',
    ...block(':root:not([data-theme])', 'dark', tokens, '  '),
    '}',
    '',
  ].join('\n');
}

export function renderTs(): string {
  const tokens = resolveAll();
  const object = (theme: ThemeName): string[] =>
    tokens.map((token) => `    '${token.name}': '${token.value[theme]}',`);
  return [
    '// SPDX-License-Identifier: MIT',
    '//',
    '// GENERATED by `node scripts/gen-tokens.ts` from src/styles/tokens/{roles,fills,radix-colors}.ts — the same',
    '// source as tokens.css, so the two cannot drift (tokens.test.ts compares them). Do not edit.',
    `// Scales: Radix Colors ${RADIX_COLORS_VERSION}, MIT License, Copyright (c) 2021 Radix.`,
    '//',
    '// For canvas/SVG code that needs a literal colour. Components read `var(--name)` (or the Tailwind utility);',
    "// this object is for code that cannot, and for tests. `TOKENS[theme]['--bg-primary']`.",
    '',
    'export const TOKENS = {',
    '  light: {',
    ...object('light'),
    '  },',
    '  dark: {',
    ...object('dark'),
    '  },',
    '} as const;',
    '',
    'export type TokenTheme = keyof typeof TOKENS;',
    'export type TokenName = keyof (typeof TOKENS)[TokenTheme];',
    '',
    "/** The CSS reference for a token: `cssVar('--chart-line')` → `var(--chart-line)`. */",
    'export function cssVar(name: TokenName): string {',
    '  return `var(${name})`;',
    '}',
    '',
  ].join('\n');
}
